# Preview PNG: both pattern tables side by side, palette 0 (bg) and sprite palette 0, 3x scale.
BG = [(0, 0, 0), (0x62, 0x62, 0x62), (0xAB, 0xAB, 0xAB), (0xFF, 0xFF, 0xFF)]
SP = [(0x20, 0x20, 0x28), (0x52, 0x28, 0x00), (0xFA, 0x9E, 0x00), (0xFF, 0xFF, 0xFF)]
