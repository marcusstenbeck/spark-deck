def blank():
    return [[0] * 8 for _ in range(8)]

def glyph_tile(rows, shadow=1, ink=3):
    t = blank()
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == '#':
                t[y][x + 1] = ink
    for y in range(8):
        for x in range(8):
            if t[y][x] == ink and y + 1 < 8 and x + 1 < 8 and t[y + 1][x + 1] == 0:
                t[y + 1][x + 1] = shadow
    return t

def from_art(art):
    return [[int(c) for c in row] for row in art]

def encode(t):
    p0 = bytes(sum(((t[y][x] & 1) << (7 - x)) for x in range(8)) for y in range(8))
    p1 = bytes(sum((((t[y][x] >> 1) & 1) << (7 - x)) for x in range(8)) for y in range(8))
    return p0 + p1

